#!/usr/bin/env python3
"""One source for the privacy policy, terms and licences. Writes the three copies the apps and the website use.

  legal/sync-legal.py           regenerate every copy
  legal/sync-legal.py --check   fail if a copy is out of date (used by the build and release scripts)
"""
import sys, pathlib
root = pathlib.Path(__file__).resolve().parent
repo = root.parent
meta = dict(l.strip().split("=", 1) for l in (root / "contact.txt").read_text().splitlines() if "=" in l)
docs = {"privacy": "Privacy Policy", "terms": "Terms of Use", "licenses": "Open-Source Licenses"}

def render(name):
    t = (root / f"{name}.md").read_text()
    return t.replace("{{UPDATED}}", meta["UPDATED"]).replace("{{CONTACT_EMAIL}}", meta["CONTACT_EMAIL"])

outputs = {}
swift = ["// Generated by legal/sync-legal.py from legal/*.md. Do not edit by hand.", "", "enum LegalText {"]
for n in docs:
    body = render(n)
    outputs[repo / "web" / "content" / "legal" / f"{n}.md"] = body
    swift.append(f'    static let {n} = #"""\n{body}\n"""#')
swift.append(f'    static let contactEmail = "{meta["CONTACT_EMAIL"]}"')
swift.append("}")
outputs[repo / "macos/Sources/REDDY/Services/LegalText.swift"] = "\n".join(swift) + "\n"

stale = []
for path, text in outputs.items():
    if "--check" in sys.argv:
        if not path.exists() or path.read_text() != text: stale.append(str(path.relative_to(repo)))
    else:
        path.parent.mkdir(parents=True, exist_ok=True); path.write_text(text)
if "--check" in sys.argv:
    if stale: print("✘ legal text is out of date; run legal/sync-legal.py:", *stale, sep="\n  "); sys.exit(1)
    if "REPLACE" in meta["CONTACT_EMAIL"]: print("! legal/contact.txt still has the placeholder support email")
    print("✔ legal text is in sync")
