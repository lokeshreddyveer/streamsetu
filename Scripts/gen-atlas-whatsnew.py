#!/usr/bin/env python3
"""Generates macos/Sources/REDDY/Atlas/Declarations/WhatsNew.swift from docs/releases/NEXT-DRAFT.md.

Each bullet under a "## " heading becomes one Setu entry ("meta.whatsNew.next.N") that says plainly it is planned and not shipped yet.
Run it whenever the draft changes; `--check` exits 1 when the committed file is out of date (for the release gates).
"""
import re, sys, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
src = root / "docs/releases/NEXT-DRAFT.md"
out = root / "macos/Sources/REDDY/Atlas/Declarations/WhatsNew.swift"

def q(s): return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

def clean(s):
    s = re.sub(r"\*\*(.+?)\*\*", r"\1", s)
    s = re.sub(r"\s*(Not checked( end to end)?|Not measured on a device yet|Checked)[^.]*\.", "", s).strip()
    return s

rows, section, n = [], "", 0
for line in src.read_text().splitlines():
    if line.startswith("## "): section = line[3:].strip(); continue
    m = re.match(r"- (.+)", line)
    if not m or section.startswith("Before this ships") or section.startswith("Android") or "No Live TV changes" in line or "as above" in line: continue
    raw = m.group(1)
    bold = re.match(r"\*\*(.+?)\*\*\.?\s*(.*)", raw)
    title = (bold.group(1) if bold else raw.split(".")[0]).strip(" .:")
    body = clean(bold.group(2) if bold else raw)
    n += 1
    plat = "[.mac, .dmgOnly]" if section == "Mac" else "[.iPhone, .iPad]" if section.startswith("iPhone") else ".all"
    rows.append((n, title, body or title, section, plat))

lines = ["// Generated by Scripts/gen-atlas-whatsnew.py from docs/releases/NEXT-DRAFT.md. Do not edit by hand.", "import Foundation", "",
         "/// What is planned for the next release, from the release draft. Every summary says it is not shipped yet.", "enum AtlasWhatsNew {", "    static let all: [AtlasEntry] = ["]
for n, title, body, section, plat in rows:
    said = title if body == title else re.sub(r"\s+([,.])", r"\1", f"{title} {body}")
    summary = f"Planned for the next release, not shipped yet: {said}"
    lines.append(f'        .make("meta.whatsNew.next.{n}", .meta, {q("Coming: " + title)}, {q(summary)}, path: ["About", "What\'s new"], reach: .modal("about"), aliases: ["upcoming", "next release", {q(title.lower())}], detail: {q("From the release notes draft, section: " + section)}, platforms: {plat}, related: ["meta.whatsNew"], reviewed: true),')
lines += ["    ]", "}", ""]
text = "\n".join(lines)
if "--check" in sys.argv:
    sys.exit(0 if out.exists() and out.read_text() == text else 1)
out.write_text(text); print(f"wrote {out} ({len(rows)} entries)")
